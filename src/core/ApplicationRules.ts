// Creates and updates Application records, filling in sensible dates when the status changes.
import { CalendarDate } from './CalendarDate';
import { DEFAULT_FOLLOW_UP_DAYS, ReminderPolicy } from './ReminderPolicy';
import { APPLICATION_STATUSES, type Application, type ApplicationStatus } from './types';

/** The fields a user can edit. id and timestamps are managed here. */
export type EditableFields = Pick<
  Application,
  'company' | 'role' | 'status' | 'appliedDate' | 'followUpDate' | 'notes' | 'jdText' | 'lastScore'
>;

export const EMPTY_FIELDS: EditableFields = {
  company: '',
  role: '',
  status: 'Saved',
  appliedDate: null,
  followUpDate: null,
  notes: '',
  jdText: '',
  lastScore: null,
};

export class ApplicationRules {
  /** Narrows a string (for example a <select> value) to a status without a type cast. */
  static isStatus(value: string): value is ApplicationStatus {
    return (APPLICATION_STATUSES as readonly string[]).includes(value);
  }

  /**
   * @param id generated by the caller (crypto.randomUUID in the browser), so tests can pass fixed ids
   * @param now the current instant; "today" is derived from it in the user's local time zone
   */
  static create(fields: Partial<EditableFields>, id: string, now: Date): Application {
    const timestamp = now.toISOString(); // an instant, so UTC is correct here
    const draft: Application = {
      ...EMPTY_FIELDS,
      ...fields,
      company: (fields.company ?? '').trim(),
      role: (fields.role ?? '').trim(),
      id,
      createdAt: timestamp,
      updatedAt: timestamp,
    };
    return ApplicationRules.fillStatusDefaults(draft, CalendarDate.today(now));
  }

  /** Applies edits. If the status changed, fills empty dates the new status needs. */
  static update(application: Application, changes: Partial<EditableFields>, now: Date): Application {
    const updated: Application = { ...application, ...changes, updatedAt: now.toISOString() };
    const statusChanged = changes.status !== undefined && changes.status !== application.status;
    return statusChanged ? ApplicationRules.fillStatusDefaults(updated, CalendarDate.today(now)) : updated;
  }

  static changeStatus(application: Application, status: ApplicationStatus, now: Date): Application {
    return ApplicationRules.update(application, { status }, now);
  }

  /**
   * Moving into a status where you wait on the company (Applied, OA, Interview):
   * - no applied date yet → assume you applied today
   * - no follow-up date yet → follow up 7 days after applying
   * Dates the user already set are never overwritten.
   */
  private static fillStatusDefaults(application: Application, today: string): Application {
    if (!ReminderPolicy.needsFollowUp(application.status)) {
      return application;
    }
    const appliedDate = application.appliedDate ?? today;
    const followUpDate = application.followUpDate ?? CalendarDate.addDays(appliedDate, DEFAULT_FOLLOW_UP_DAYS);
    return { ...application, appliedDate, followUpDate };
  }
}
